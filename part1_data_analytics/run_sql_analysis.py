"""Run every named query in sql/traffic_analysis.sql and save each result.

Results go to part1_data_analytics/results/<query name>.csv and are also
collected into results/sql_results.md for easy reading.

Run from the repository root (after load_sqlite):

    python -m part1_data_analytics.run_sql_analysis
"""

import logging
import re
import sqlite3
import sys
from pathlib import Path

import pandas as pd

from common import config
from common.logging_setup import setup_logging

logger = logging.getLogger(__name__)

PART1_DIR = config.ROOT_DIR / "part1_data_analytics"
SQL_FILE = PART1_DIR / "sql" / "traffic_analysis.sql"
RESULTS_DIR = PART1_DIR / "results"
LOG_FILE = PART1_DIR / "part1.log"


def parse_named_queries(sql_text: str) -> dict:
    """Split the SQL file into {name: query} using '-- name: <name>' markers."""
    parts = re.split(r"^--\s*name:\s*(\S+)\s*$", sql_text, flags=re.MULTILINE)
    # parts = [preamble, name1, body1, name2, body2, ...]
    queries = {}
    for name, body in zip(parts[1::2], parts[2::2]):
        # stop at the next section header so comments between queries are not included
        body = body.split("-- ----")[0].strip().rstrip(";")
        queries[name] = body
    return queries


def run_queries(conn: sqlite3.Connection, queries: dict) -> dict:
    results = {}
    for name, sql in queries.items():
        try:
            df = pd.read_sql_query(sql, conn)
        except (sqlite3.Error, pd.errors.DatabaseError):
            logger.error("Query '%s' failed", name, exc_info=True)
            raise
        out = RESULTS_DIR / f"{name}.csv"
        df.to_csv(out, index=False)
        logger.info("Query '%s' returned %d rows, saved to %s", name, len(df), out.relative_to(config.ROOT_DIR))
        results[name] = df
    return results


def write_markdown(results: dict) -> None:
    lines = ["# Part 1 SQL results", "", "Generated by `run_sql_analysis.py` from `sql/traffic_analysis.sql`.", ""]
    for name, df in results.items():
        lines += [f"## {name}", ""]
        shown = (df if len(df) <= 40 else df.head(40)).convert_dtypes()  # nullable ints: no 1.7e+07
        lines.append(shown.to_markdown(index=False))
        if len(df) > 40:
            lines.append(f"\n*First 40 of {len(df)} rows. Full result in `{name}.csv`.*")
        lines.append("")
    out = RESULTS_DIR / "sql_results.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    logger.info("Wrote combined results to %s", out.relative_to(config.ROOT_DIR))


def main() -> int:
    setup_logging(LOG_FILE, append=True)  # continues the log started by load_sqlite
    if not config.SQLITE_DB.exists():
        logger.error("Database not found at %s. Run 'python -m part1_data_analytics.load_sqlite' first.", config.SQLITE_DB)
        return 1
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    try:
        queries = parse_named_queries(SQL_FILE.read_text(encoding="utf-8"))
        logger.info("Found %d named queries in %s", len(queries), SQL_FILE.name)
        with sqlite3.connect(config.SQLITE_DB) as conn:
            results = run_queries(conn, queries)
        write_markdown(results)
    except (OSError, sqlite3.Error, pd.errors.DatabaseError):
        logger.error("SQL analysis did not complete", exc_info=True)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
